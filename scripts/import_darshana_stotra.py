#!/usr/bin/env python3
"""Copy the मूलम् of some stotras from the darshana repo into this one.

darshana keeps a few stotras (with notes/commentary) under
contents/advaita/stotra/. This site only wants their verses, for
chanting: every <div class="shloka"> is copied, along with Markdown
headings (`#` … `######`) that sit outside any div, in their original
order. Everything else (glosses and notes, including headings inside
them, prose, frontmatter) is left behind. The copies are
site-only — no `dict:` block — since darshana already puts them in its
own dictionary.

The generated files are meant to be committed. Re-run this whenever the
verses change in darshana (notes-only changes there don't matter):

    python3 scripts/import_darshana_stotra.py --darshana ../darshana
    python3 scripts/import_darshana_stotra.py      # shallow-clones darshana from GitHub

Each target book directory is owned by this script: its meta.yaml and
chapter .md files are rewritten every run, and a generated .md whose
source file is gone is removed. Edit STOTRAS below to add or move one.
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

REPO_URL = "https://github.com/vagvibha/darshana.git"
ROOT = Path(__file__).resolve().parent.parent  # this repo

# darshana book dir (relative to the darshana repo) -> book dir here
STOTRAS = [
    ("contents/advaita/stotra/dms", "contents/stotra/shiva/dakshinamurti"),
    ("contents/advaita/stotra/manishapanchakam", "contents/stotra/misc/manishapanchakam"),
    ("contents/advaita/stotra/spanchaka", "contents/stotra/misc/sadhanapanchakam"),
]

MARKER = "GENERATED by scripts/import_darshana_stotra.py"
# Book meta keys carried over from darshana's meta.yaml (the rest is set here).
KEEP_META = ("title", "author")

FRONTMATTER_RE = re.compile(r"\A---\n.*?\n---\n", re.S)
SHLOKA_OPEN_RE = re.compile(r'<div\s+class="shloka"[^>]*>')
DIV_TAG_RE = re.compile(r"<div\b[^>]*>|</div>")


HEADING_RE = re.compile(r"^#{1,6}\s+\S.*$", re.M)
FENCE_RE = re.compile(r"^(```|~~~).*?^\1[ \t]*$", re.M | re.S)
# darshana's gloss shorthand (<notes>…</notes>, <tika …>…</tika>, …): any
# lowercase tag other than plain HTML ones counts as a container to skip.
SHORTHAND_RE = re.compile(r"<(/?)([a-z][a-z0-9_-]*)\b[^>]*?(/?)>")
NOT_CONTAINERS = {"b", "i", "u", "em", "strong", "br", "a", "span", "sup", "sub",
                  "img", "audio", "video", "source", "p", "small", "dict", "topic", "dictref"}


def items(text: str) -> list[tuple[str, str]]:
    """("heading", line) / ("shloka", inner text), in document order.

    Only top-level things count: a shloka div or heading nested inside
    another div (or a gloss shorthand tag like <notes>, or a fenced code
    block) belongs to that commentary and is skipped."""
    # blank out fenced code so a "# comment" inside it isn't a heading
    text = FENCE_RE.sub(lambda m: re.sub(r"[^\n]", " ", m.group(0)), text)
    # where each top-level shloka div starts/ends, and every region that
    # is inside some container (div or shorthand tag)
    inside: list[tuple[int, int]] = []
    shlokas: list[tuple[int, int, int]] = []  # (start, inner_start, inner_end)
    stack: list[tuple[str, int, re.Match | None]] = []
    tags = sorted(
        [(m.start(), m.end(), "div", m.group(0) != "</div>", m) for m in DIV_TAG_RE.finditer(text)]
        + [(m.start(), m.end(), m.group(2), not m.group(1), m)
           for m in SHORTHAND_RE.finditer(text)
           if m.group(2) not in NOT_CONTAINERS and m.group(2) != "div" and not m.group(3)],
        key=lambda t: t[0])
    for start, end, name, opening, m in tags:
        if opening:
            stack.append((name, start, m))
            continue
        # close the innermost matching open tag (tolerates stray closers)
        for k in range(len(stack) - 1, -1, -1):
            if stack[k][0] == name:
                oname, ostart, om = stack[k]
                del stack[k:]
                if not stack:
                    inside.append((ostart, end))
                    if name == "div" and SHLOKA_OPEN_RE.match(om.group(0)):
                        shlokas.append((ostart, om.end(), start))
                break
    if stack:
        sys.exit(f"unclosed <{stack[0][0]}> at offset {stack[0][1]}")

    out: list[tuple[int, str, str]] = [(s, "shloka", text[a:b]) for s, a, b in shlokas]
    for h in HEADING_RE.finditer(text):
        if not any(a <= h.start() < b for a, b in inside):
            out.append((h.start(), "heading", h.group(0).rstrip()))
    return [(kind, val) for _, kind, val in sorted(out)]


def clean(inner: str) -> str:
    """Drop darshana-only markup from a verse, keep its text."""
    inner = re.sub(r"<dictref\b[^>]*/>", "", inner)
    inner = re.sub(r"<(dict|topic)\b[^>]*/>", "", inner)
    inner = re.sub(r"</?(dict|topic)\b[^>]*>", "", inner)
    lines = [l.rstrip() for l in inner.strip("\n").split("\n")]
    return "\n".join(lines).strip()


def import_book(src: Path, dst: Path) -> None:
    meta = yaml.safe_load((src / "meta.yaml").read_text(encoding="utf-8")) or {}
    book = {k: meta[k] for k in KEEP_META if k in meta}
    book.update({"skip_text_index": True, "shloka_toc": False})
    dst.mkdir(parents=True, exist_ok=True)
    (dst / "meta.yaml").write_text(
        f"# {MARKER} from darshana/{src.relative_to(src.parents[3])} — don't edit by hand.\n"
        + yaml.safe_dump(book, allow_unicode=True, sort_keys=False),
        encoding="utf-8",
    )

    written: set[Path] = set()
    chapters = sorted(p for p in src.iterdir() if p.is_dir())
    for ch in chapters:
        for md in sorted(ch.glob("*.md")):
            body = FRONTMATTER_RE.sub("", md.read_text(encoding="utf-8"), count=1)
            parts = []
            n = 0
            for kind, val in items(body):
                if kind == "heading":
                    parts.append(val)
                elif (v := clean(val)):
                    parts.append(f'<div class="shloka">\n{v}\n</div>')
                    n += 1
            if not n:
                print(f"  {md.name}: no shlokas — skipped")
                continue
            out = dst / ch.name / md.name
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(
                f"<!-- {MARKER} from darshana — don't edit by hand. -->\n\n"
                + "\n\n".join(parts) + "\n",
                encoding="utf-8",
            )
            written.add(out)
            print(f"  {out.relative_to(ROOT)}: {n} shloka(s), {len(parts) - n} heading(s)")

    # remove generated files whose source is gone
    for old in dst.glob("*/*.md"):
        if old not in written and MARKER in old.read_text(encoding="utf-8").split("\n", 1)[0]:
            old.unlink()
            print(f"  removed stale {old.relative_to(ROOT)}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--darshana", type=Path,
                    help="local darshana checkout (default: shallow-clone it from GitHub)")
    ap.add_argument("--ref", default="main", help="branch to clone when --darshana isn't given")
    args = ap.parse_args()

    tmp = None
    try:
        if args.darshana:
            darshana = args.darshana.resolve()
        else:
            tmp = tempfile.mkdtemp(prefix="darshana-")
            subprocess.run(["git", "clone", "-q", "--depth", "1", "--branch", args.ref, REPO_URL, tmp],
                           check=True)
            darshana = Path(tmp)
        for src_rel, dst_rel in STOTRAS:
            src = darshana / src_rel
            if not (src / "meta.yaml").is_file():
                sys.exit(f"{src}: not a book directory (no meta.yaml)")
            print(f"{src_rel} -> {dst_rel}")
            import_book(src, ROOT / dst_rel)
    finally:
        if tmp:
            shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()
